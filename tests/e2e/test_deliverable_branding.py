"""One product name: "Database Modernizer Assessment Tool" (#954).

No rendered deliverable may carry "ATX", "AWS Transform" or the standalone word
"transform" in any case (``tests/branding.py``; "transformation" is ordinary prose). The check runs over every file the report step wrote for each sample: the
HTML reports (markup and attributes, with the inline script and style bodies
removed, since those hold browser API names such as the canvas ``setTransform``
call and the CSS ``transform`` property, not text anyone reads), the Markdown
report, the PDF text and its document metadata.
"""

from __future__ import annotations

import io
from pathlib import Path

from pypdf import PdfReader

from tests.branding import hits as found
from tests.branding import visible_html
from tests.e2e.pipeline import PipelineResult


def _texts(path: Path) -> list[str]:
    data = path.read_bytes()
    if path.suffix == ".pdf":
        reader = PdfReader(io.BytesIO(data))
        meta = " ".join(str(v) for v in (reader.metadata or {}).values())
        return [meta, *[(p.extract_text() or "") for p in reader.pages]]
    text = data.decode("utf-8", "replace")
    if path.suffix == ".html":
        text = visible_html(text)
    return [text]


def test_no_deliverable_names_another_product(run: PipelineResult) -> None:
    paths = [Path(p) for p in run.report.get("paths", [])]
    assert {p.suffix for p in paths} >= {".html", ".md", ".pdf"}
    hits: list[str] = []
    for path in paths:
        for text in _texts(path):
            hits.extend(f"{path.name}: {h}" for h in found(text))
    assert hits == []


def test_the_analysis_report_names_this_product(run: PipelineResult) -> None:
    html = run.html("analysis-report").read_text()
    assert "Generated by Database Modernizer Assessment Tool" in html
