"""The shells that every interactive report is built from carry one product name (#954)."""

from __future__ import annotations

from pathlib import Path

import pytest

from tests.branding import hits, visible_html

REPO = Path(__file__).resolve().parents[3]


def test_the_report_template_shell_names_this_product() -> None:
    shell = (REPO / "src/report/templates/analysis_report.html.tpl").read_text()
    assert hits(visible_html(shell)) == []
    assert "Generated by Database Modernizer Assessment Tool" in shell


def test_the_ui_export_names_this_product() -> None:
    source = (REPO / "src/ui/src/utils/ExportReport.js").read_text()
    assert "Generated by Database Modernizer Assessment Tool" in source
    assert "Generated by AWS Transform" not in source
    assert 'aria-label="AWS Transform"' not in source


@pytest.mark.parametrize(
    "text",
    [
        "The transformation of the schema takes two waves.",
        "A Lambda function transforms and routes changes.",
        "Data transformations run in the application layer.",
        "Latex and Matxx are not products.",
    ],
)
def test_ordinary_prose_passes(text: str) -> None:
    assert hits(text) == []


@pytest.mark.parametrize(
    "text",
    [
        "Generated by AWS Transform",
        "generated by aws   transform",
        "Run the transform step first.",
        "TRANSFORM the rows.",
        "Handled by ATX jobs.",
        "(atx)",
    ],
)
def test_another_product_name_fails(text: str) -> None:
    assert hits(text) != []


def test_script_and_style_bodies_are_not_text() -> None:
    html = (
        "<style>.a{transform:scale(1)}</style><p>ok</p>"
        "<script>ctx.setTransform(1,0,0,1,0,0); resetTransform()</script>"
    )
    assert hits(visible_html(html)) == []
    assert hits(visible_html('<p aria-label="AWS Transform">x</p>')) != []
